#!/usr/bin/env python3
"""Generate the androidx library `R` classes the app's dex is missing.

`aapt2 link --java` emits an `R.java` for the application package only. A real
AGP build also generates one per AAR, because library bytecode refers to its own
`androidx.appcompat.R`, `androidx.core.R`, and so on. This build merges every
library's resources into the application package, so those library `R` classes
never existed.

That gap does not fail the build. `d8` accepts it, the APK installs, and ART
only discovers the problem when it verifies a class whose static state reads
those fields -- surfacing as a launch crash, not a build error.

Each library `R` field is emitted as a reference to the identically named field
of the application `R`. That is exact rather than approximate: the merge gave
every library resource an id in the one application table under the same name,
so the two fields denote the same resource. Nothing is hardcoded and no id is
invented.

Fields the application `R` does not declare are skipped, because a library may
declare a resource the merge dropped or renamed; referencing it would not
compile.
"""
import os
import re
import subprocess
import sys
import zipfile
from pathlib import Path

R_FIELD = re.compile(r"public static final (int\[\]|int)\s+(\w+)\s*(?:=|;)")
R_CLASS = re.compile(r"public static final class (\w+)")


def app_r_fields(app_r_java):
    """Map (inner class, field name) -> 'int' | 'int[]', from the generated R.java.

    Declarations look like `public static final int foo=0x7f010000;` and
    `public static final int[] Foo = {` followed by one id per line, so only the
    start of the declaration needs to match.
    """
    fields = {}
    current = None
    for line in app_r_java.splitlines():
        match = R_CLASS.search(line)
        if match:
            current = match.group(1)
            continue
        field = R_FIELD.search(line)
        if field and current:
            fields[(current, field.group(2))] = "int[]" if field.group(1) == "int[]" else "int"
    return fields


def aar_package(aar):
    with zipfile.ZipFile(aar) as z:
        manifest = z.read("AndroidManifest.xml").decode("utf-8", "replace")
    match = re.search(r'package="([^"]+)"', manifest)
    return match.group(1) if match else None


def parse_r_txt(text):
    """Yield (kind, type, name). kind is 'int' or 'int[]'."""
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            continue
        if line.startswith("int[] "):
            parts = line.split()
            yield "int[]", parts[1], parts[2]
        elif line.startswith("int "):
            parts = line.split()
            if len(parts) >= 3:
                yield "int", parts[1], parts[2]


def main():
    if len(sys.argv) != 5:
        raise SystemExit(
        "usage: gen-library-r.py <app-R.java> <app-package> <out-dir> <jar-dir>"
    )
    app_r_java, app_package, out_dir, jar_dir = (
        sys.argv[1], sys.argv[2], Path(sys.argv[3]), Path(sys.argv[4])
    )

    available = app_r_fields(Path(app_r_java).read_text())
    aars = sorted(jar_dir.glob("*.aar"))
    if not aars:
        print("gen-library-r: no AARs found, nothing to do")
        return 0

    generated, skipped = 0, 0
    for aar in aars:
        package = aar_package(aar)
        if not package or package == app_package:
            continue
        try:
            with zipfile.ZipFile(aar) as z:
                if "R.txt" not in z.namelist():
                    continue
                entries = list(parse_r_txt(z.read("R.txt").decode("utf-8", "replace")))
        except (zipfile.BadZipFile, KeyError):
            continue

        by_type = {}
        for kind, rtype, name in entries:
            if (rtype, name) not in available:
                skipped += 1
                continue
            by_type.setdefault(rtype, []).append((name, available[(rtype, name)]))

        if not by_type:
            continue

        target = out_dir / Path(package.replace(".", "/")) / "R.java"
        target.parent.mkdir(parents=True, exist_ok=True)
        body = [
            "// Generated by scripts/gen-library-r.py. Do not edit.",
            f"// Delegates to the merged application resource table ({app_package}).",
            "package %s;" % package,
            "",
            "public final class R {",
        ]
        for rtype in sorted(by_type):
            body.append(f"    public static final class {rtype} {{")
            for name, kind in sorted(by_type[rtype]):
                body.append(
                    f"        public static final {kind} {name} = "
                    f"{app_package}.R.{rtype}.{name};"
                )
            body.append("    }")
        body.append("}")
        target.write_text("\n".join(body) + "\n", encoding="utf-8")
        generated += 1

    print(
        f"gen-library-r: {generated} library R classes, "
        f"{skipped} entries not present in the app R (skipped)"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())